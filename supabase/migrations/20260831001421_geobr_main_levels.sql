create table if not exists public.geobr_main_levels (
    id bigint generated by default as identity primary key,
    campaign_order integer not null unique check (campaign_order > 0),
    name text not null check (char_length(name) between 1 and 64),
    creator text not null default 'Equipe GeoBR' check (char_length(creator) between 1 and 40),
    description text not null default '' check (char_length(description) <= 300),
    difficulty text not null check (
        lower(difficulty) in (
            'auto', 'easy', 'normal', 'hard', 'harder', 'insane', 'demon',
            'easy demon', 'medium demon', 'hard demon', 'insane demon', 'extreme demon'
        )
    ),
    stars smallint not null default 0 check (stars between 0 and 10),
    song text not null default '' check (char_length(song) <= 100),
    platformer boolean not null default false,
    gmd_path text not null unique check (
        char_length(gmd_path) between 5 and 240
        and gmd_path !~ '(^/|\\\\|://)'
        and position('..' in gmd_path) = 0
        and lower(gmd_path) ~ '\\.(gmd|gmd2|lvl)$'
    ),
    file_version integer not null default 1 check (file_version between 1 and 1000000),
    published boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    check (id between 1 and 2000000000)
);

comment on table public.geobr_main_levels is
    'Catalogo dinamico de Main Levels consumido pelo GeoBR Mod.';
comment on column public.geobr_main_levels.gmd_path is
    'Caminho relativo dentro do bucket publico geobr-main-levels; nunca uma URL externa.';

