drop function if exists public.geobr_create_collab_room(text, text);
create function public.geobr_create_collab_room(
    p_title text,
    p_display_name text
)
returns table (
    room_id uuid,
    room_code text,
    room_title text,
    member_role text,
    level_snapshot text,
    operation_cursor bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    current_user_id uuid := auth.uid();
    created_room public.geobr_collab_rooms%rowtype;
    generated_code text;
begin
    if current_user_id is null then
        raise exception 'authentication required' using errcode = '42501';
    end if;
    if char_length(trim(p_title)) not between 1 and 40 then
        raise exception 'invalid room title' using errcode = '22023';
    end if;
    if char_length(trim(p_display_name)) not between 1 and 32 then
        raise exception 'invalid display name' using errcode = '22023';
    end if;

    loop
        generated_code := upper(substr(md5(gen_random_uuid()::text), 1, 8));
        exit when not exists (
            select 1 from public.geobr_collab_rooms room where room.code = generated_code
        );
    end loop;

    insert into public.geobr_collab_rooms (code, title, owner_id)
    values (generated_code, trim(p_title), current_user_id)
    returning * into created_room;

    insert into public.geobr_collab_members (room_id, user_id, role, display_name)
    values (created_room.id, current_user_id, 'owner', trim(p_display_name));
    insert into public.geobr_collab_snapshots (room_id, updated_by)
    values (created_room.id, current_user_id);

    return query select
        created_room.id,
        created_room.code,
        created_room.title,
        'owner'::text,
        ''::text,
        0::bigint;
end;
$$;

drop function if exists public.geobr_join_collab_room(text, text);
create function public.geobr_join_collab_room(
    p_code text,
    p_display_name text
)
returns table (
    room_id uuid,
    room_code text,
    room_title text,
    member_role text,
    level_snapshot text,
    operation_cursor bigint
)
language plpgsql
security definer
set search_path = ''
as $$
declare
    current_user_id uuid := auth.uid();
    target_room public.geobr_collab_rooms%rowtype;
    snapshot_text text;
    snapshot_cursor bigint;
begin
    if current_user_id is null then
        raise exception 'authentication required' using errcode = '42501';
    end if;
    if char_length(trim(p_display_name)) not between 1 and 32 then
        raise exception 'invalid display name' using errcode = '22023';
    end if;

    select room.* into target_room
    from public.geobr_collab_rooms room
    where room.code = upper(trim(p_code)) and room.active = true;
    if target_room.id is null then
        raise exception 'room not found' using errcode = 'P0002';
    end if;

    insert into public.geobr_collab_members (room_id, user_id, role, display_name)
    values (target_room.id, current_user_id, 'editor', trim(p_display_name))
    on conflict (room_id, user_id) do update
    set display_name = excluded.display_name;

    select snapshot.level_string, snapshot.operation_cursor
    into snapshot_text, snapshot_cursor
    from public.geobr_collab_snapshots snapshot
    where snapshot.room_id = target_room.id;

    return query select
        target_room.id,
        target_room.code,
        target_room.title,
        coalesce((
            select member.role
            from public.geobr_collab_members member
            where member.room_id = target_room.id and member.user_id = current_user_id
        ), 'editor'::text),
        coalesce(snapshot_text, ''::text),
        coalesce(snapshot_cursor, 0::bigint);
end;
$$;

drop function if exists public.geobr_save_collab_snapshot(uuid, text);
drop function if exists public.geobr_save_collab_snapshot(uuid, text, bigint);
create function public.geobr_save_collab_snapshot(
    p_room_id uuid,
    p_level_string text,
    p_operation_cursor bigint
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
    next_revision bigint;
begin
    if not (select geobr_private.can_edit_collab(p_room_id)) then
        raise exception 'room edit permission required' using errcode = '42501';
    end if;
    if octet_length(coalesce(p_level_string, '')) > 8388608 then
        raise exception 'snapshot exceeds 8 MiB' using errcode = '22001';
    end if;
    if p_operation_cursor < 0 then
        raise exception 'invalid operation cursor' using errcode = '22023';
    end if;

    insert into public.geobr_collab_snapshots (
        room_id, revision, operation_cursor, level_string, updated_by, updated_at
    ) values (
        p_room_id, 1, p_operation_cursor, coalesce(p_level_string, ''), auth.uid(), now()
    )
    on conflict (room_id) do update
    set revision = public.geobr_collab_snapshots.revision + 1,
        level_string = excluded.level_string,
        operation_cursor = excluded.operation_cursor,
        updated_by = excluded.updated_by,
        updated_at = excluded.updated_at
    returning revision into next_revision;

    return next_revision;
end;
$$;

