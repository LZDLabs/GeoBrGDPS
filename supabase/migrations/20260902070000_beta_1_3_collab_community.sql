alter table public.geobr_main_levels
    add column if not exists coins smallint not null default 3
    check (coins between 0 and 3);

update public.geobr_main_levels set coins = 3 where coins is null;

create table if not exists public.geobr_community_messages (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    username text not null check (char_length(username) between 1 and 32),
    message text not null check (char_length(message) between 1 and 160),
    account_id bigint not null default 0,
    player_id bigint not null default 0,
    created_at timestamptz not null default now()
);

create index if not exists geobr_community_messages_created_idx
    on public.geobr_community_messages (created_at desc, id desc);
create index if not exists geobr_community_messages_user_idx
    on public.geobr_community_messages (user_id);

alter table public.geobr_community_messages enable row level security;

drop policy if exists "GeoBR community is public" on public.geobr_community_messages;
create policy "GeoBR community is public"
on public.geobr_community_messages for select to anon, authenticated
using (true);

drop policy if exists "GeoBR users send own messages" on public.geobr_community_messages;
create policy "GeoBR users send own messages"
on public.geobr_community_messages for insert to authenticated
with check (user_id = (select auth.uid()));

revoke all on public.geobr_community_messages from anon, authenticated;
grant select on public.geobr_community_messages to anon, authenticated;
grant insert on public.geobr_community_messages to authenticated;
grant all on public.geobr_community_messages to service_role;
grant usage, select on sequence public.geobr_community_messages_id_seq to authenticated, service_role;
