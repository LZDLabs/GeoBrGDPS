#!/usr/bin/env python3
"""Writes src/compat/ThunkStubs.cpp from the Android build of the mod.

The Geode 6 bindings define some GD vtables inside the mod (classes whose
constructor GeoBR never calls, e.g. PlayLayer). Those copies point at GD's
"this-adjusting thunks" (_ZThn* / _ZTv*), whose offsets come from the
bindings' class layout; when the game's layout differs by a few bytes the
thunk does not exist in libcocos2dcpp.so and Android refuses to load the mod
("cannot locate symbol _ZThn13992_N9PlayLayer..."). The vtables are never
used, so weak empty definitions are enough to let the mod load.

Usage: gen_thunk_stubs.py <llvm-nm> <geobr.geobrmod.android64.so> <out.cpp>
Rebuild after running it (the stubs then appear as defined, not imported).
"""
import subprocess, sys

nm, so, out = sys.argv[1:4]
names = sorted({line.split()[-1] for line in subprocess.run([nm, "-D", "--undefined-only", so], capture_output=True, text=True, check=True).stdout.splitlines()
                if line.split() and line.split()[-1].startswith(("_ZThn", "_ZTv"))})
try:
    old = open(out).read()
    names = sorted(set(names) | {l.split("void ")[1].split("(")[0] for l in old.splitlines() if l.startswith("GEOBR_THUNK void ")})
except FileNotFoundError:
    pass
with open(out, "w") as f:
    f.write("// Generated by tools/gen_thunk_stubs.py: see that file for why.\n")
    f.write("#if defined(__ANDROID__)\n#define GEOBR_THUNK extern \"C\" __attribute__((weak, visibility(\"hidden\")))\n")
    for n in names:
        f.write(f"GEOBR_THUNK void {n}() {{}}\n")
    f.write("#endif\n")
print(len(names), "thunk stubs")
